/**
 * Generate which archived configuration + style pairs actually hold measurement values.
 * Many archived records are valid responses with no measurements (the source never
 * measured that size or cushion layout). Search uses this list so those choices are
 * shown as unavailable instead of failing after the user picks them.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import dotenv from 'dotenv';
import {
  archivedStyleKey,
  countArchivedMeasurements,
  isArchivedStyleMismatch,
} from '../server/vercel-routes/cw/archive.ts';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
dotenv.config({ path: path.join(root, '.env.local'), quiet: true });
const directory = process.env.CW_ARCHIVE_DIR;
if (!directory) throw new Error('CW_ARCHIVE_DIR is required');
const readJson = async (relative: string) =>
  JSON.parse(await fs.readFile(path.join(directory, relative), 'utf8'));
const tuples = await readJson('measurement-tuples.json');
const availability: Record<string, string[]> = {};
let available = 0;
for (const tuple of tuples) {
  const reference = String(tuple.reference).toUpperCase();
  availability[reference] ||= [];
  const record = await readJson(`measurements/${tuple.file}`);
  if (
    record.httpStatus !== 200 ||
    Number(record.data?.status) !== 200 ||
    isArchivedStyleMismatch(tuple.style, tuple.styleCode, record.data?.content) ||
    !countArchivedMeasurements(record.data?.content)
  )
    continue;
  const key = archivedStyleKey(tuple.style, tuple.styleCode);
  if (!availability[reference].includes(key)) availability[reference].push(key);
  available++;
}
for (const list of Object.values(availability)) list.sort();
const sorted = Object.fromEntries(
  Object.entries(availability).sort(([a], [b]) => a.localeCompare(b))
);
const source = `// Generated by scripts/cw-archive-availability.ts. Server only.\n// Archived reference -> style keys whose record holds measurement values. A reference\n// with an empty list was archived but has no measurements for any style.\nexport const archivedStyleAvailability: Record<string, string[]> = ${JSON.stringify(sorted)};\n`;
await fs.writeFile(path.join(root, 'server/vercel-routes/cw/archive-availability.ts'), source);
console.log(
  JSON.stringify({
    references: Object.keys(sorted).length,
    availableSelections: available,
    emptyReferences: Object.values(sorted).filter(list => !list.length).length,
  })
);
